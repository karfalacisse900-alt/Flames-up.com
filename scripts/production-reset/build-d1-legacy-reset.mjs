#!/usr/bin/env node

import fs from "node:fs";

const [, , tablesJsonPath, outputSqlPath] = process.argv;

if (!tablesJsonPath || !outputSqlPath) {
  console.error("Usage: build-d1-legacy-reset.mjs <wrangler-tables-json> <output-sql>");
  process.exit(1);
}

const deleteOrder = [
  "status_likes",
  "discover_likes",
  "comment_likes",
  "likes",
  "saved_posts",
  "saved_places",
  "comments",
  "reports",
  "private_info_reports",
  "impersonation_reports",
  "content_match_events",
  "blocks",
  "notifications",
  "push_tokens",
  "message_typing",
  "messages",
  "group_messages",
  "group_chat_members",
  "group_chats",
  "user_presence",
  "media_assets",
  "media_backups",
  "moderation_results",
  "moderation_jobs",
  "moderation_events",
  "moderation_notes",
  "moderation_actions",
  "admin_actions",
  "audit_logs",
  "user_restrictions",
  "anti_abuse_signals",
  "anti_bot_signals",
  "client_events",
  "ownership_disputes",
  "remix_permission_requests",
  "publisher_applications",
  "creator_credit_ledger",
  "creator_portfolio_items",
  "credit_chains",
  "creators",
  "ownership_records",
  "reputation_events",
  "reputation_profiles",
  "posts",
  "discover_posts",
  "statuses",
  "favorite_sounds",
  "phone_login_codes",
  "follows",
  "friendships",
  "friend_requests",
  "places",
  "account_deletion_events",
  "deleted_account_safety_records",
  "account_identities",
  "users",
];

const raw = JSON.parse(fs.readFileSync(tablesJsonPath, "utf8"));
const rows = Array.isArray(raw)
  ? raw.flatMap((entry) => entry?.results ?? [])
  : raw?.results ?? [];
const existing = new Set(
  rows
    .map((row) => String(row?.name ?? "").trim())
    .filter((name) => name && !name.startsWith("sqlite_")),
);

const deletes = deleteOrder.filter((table) => existing.has(table));
const skipped = deleteOrder.filter((table) => !existing.has(table));

const sql = [
  "-- Generated by scripts/production-reset/build-d1-legacy-reset.mjs.",
  "-- Deletes legacy app data rows only. Does not drop tables or infrastructure.",
  "PRAGMA foreign_keys = OFF;",
  "",
  ...deletes.map((table) => `DELETE FROM ${table};`),
  "",
  "PRAGMA foreign_keys = ON;",
  "",
].join("\n");

fs.writeFileSync(outputSqlPath, sql);

console.log(
  JSON.stringify(
    {
      existingTables: existing.size,
      resetTables: deletes.length,
      skippedMissingTables: skipped.length,
      outputSqlPath,
    },
    null,
    2,
  ),
);
